"""Experimental native-recompile back end: typed IR statements -> portable C.

Where emit0 targets the original Borland toolchain byte-for-byte, this back end
targets MODERN platforms: the generated translation unit is self-contained
(the runtime fragments in c0_runtime/ are embedded verbatim, no external
headers beyond libc/libm/Win32) and compiles with gcc or clang on any modern
OS -- `cc out.c -lm` on POSIX, MinGW-w64 gcc or clang on Windows (the runtime
carries #ifdef _WIN32 paths for its terminal/keyboard/timing bits).
GOSUB/RETURN use the labels-as-values extension, so gcc/clang specifically,
not MSVC.

Two variants of the output shape (see emit_c): `standalone=False` emits an
#include of tb_runtime.h instead of embedding the runtime, for linking many
programs against one libtbrt.a (`make` in c0_runtime/); `sdl=True` selects
the SDL2 video backend, presenting the graphics framebuffer in a real
window with the window's keyboard feeding INKEY$/INSTAT.

Fidelity is behavioral, not byte-exact, and deliberately fail-loud in the
repo's style: an IR node, intrinsic, or type combination outside the
implemented vocabulary raises ValueError rather than mistranslating. The
implemented semantics follow the Turbo Basic handbook:

- unsuffixed and `!` variables are C `float` (TB singles), `%` is `short`
  with CINT banker's rounding on store, `#` is `double`, `$` is a heap
  C string (allocations are never freed -- recompiled programs are
  short-lived by assumption);
- \\ MOD AND OR XOR NOT operate on CINT-rounded 16-bit integers;
- PRINT reproduces the GW-BASIC family layout: sign-or-space before a
  number, trailing space after, `.5` without a leading zero, 7 significant
  digits (single precision), 14-column comma zones untouched (the decoder
  never produces comma items -- TAB/SPC arrive as Call items);
- FOR/WHILE/DO compile to explicit test/jump label pairs so EXIT FOR /
  EXIT LOOP and cross-statement GOTO keep working exactly as in the flat IR.

Machine access runs against the emulated real-mode machine in
machine.c: PEEK/POKE/DEF SEG/BLOAD/BSAVE address a private zeroed 1 MiB
array, OUT/INP are 64 K port latches, WAIT returns at once, REG is real
storage with a no-op CALL INTERRUPT, CHAIN execs the named file, and
CALL ABSOLUTE transpiles but aborts if reached (there is no machine code
to run).

Unsupported (raises): string DEF FN, DIM rank > 2, and any intrinsic not
listed in _NUM_FUNCS/_STR_FUNCS.
"""

from __future__ import annotations

from importlib.resources import files as _res_files

from tbx import ir

# The C runtime lives beside this module in c0_runtime/ as standalone units:
# each .c includes tb_runtime.h and compiles on its own, so the runtime also
# builds as an ordinary C library. emit amalgamates header + fragments
# (stripping the include lines) into one self-contained translation unit.
# Order matters (later fragments call earlier ones), hence an explicit
# manifest rather than a directory glob.
_RUNTIME_FRAGMENTS = (
    "core.c",      # error trapping, console PRINT, clock, numbers, strings, INPUT
    "fileio.c",    # sequential/random-access file I/O, WRITE, PRINT USING, MKx$/CVx
    "terminal.c",  # RND, INSTAT, ANSI terminal control, INKEY$, FILES, BIN$
    "graphics.c",  # framebuffer graphics: SCREEN, PSET, LINE, CIRCLE, PAINT, DRAW...
    "play.c",      # PLAY: MML decoding to the WAV-file surrogate
    "events.c",    # ON TIMER polling, MTIMER, the GOSUB label stack
    "machine.c",   # emulated real-mode memory, ports, REG buffer, CHAIN
    "sdl.c",       # optional SDL2 window (-DTB_SDL=1); empty otherwise
)


def _amalgamate() -> str:
    d = _res_files("tbx") / "c0_runtime"
    parts = ["/* generated by tbx --emit-c : Turbo Basic recompiled to C */\n"]
    parts.append((d / "tb_runtime.h").read_text())
    for name in _RUNTIME_FRAGMENTS:
        parts.append((d / name).read_text().replace('#include "tb_runtime.h"\n', "", 1))
    return "".join(parts)


