def _suffix_ty(name: str) -> str:
    return {"%": "INT", "&": "LNG", "!": "SGL", "#": "DBL", "$": "STR"}.get(name[-1], "NUM")


def _base(name: str) -> str:
    return name.rstrip("%&!#$")


def _cstr(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f'\\{ord(ch):03o}')
    out.append('"')
    return "".join(out)


class _Raw:
    """A pre-rendered C fragment standing in for an Expr in assign()."""

    def __init__(self, code: str, is_str: bool):
        self.code = code
        self.is_str = is_str


def _is_str(e) -> bool:
    if isinstance(e, _Raw):
        return e.is_str
    if isinstance(e, ir.StrLit):
        return True
    if isinstance(e, (ir.Var, ir.ArrayRef, ir.Call, ir.FnCall, ir.Nullary)):
        return e.name.endswith("$")
    if isinstance(e, ir.BinOp) and e.op == "+":
        return _is_str(e.lhs)
    if isinstance(e, ir.Group):
        return _is_str(e.inner)
    return False


class _Unsupported(ValueError):
    pass


class _Gen:
    """One translation: collects declarations while rendering the body."""

    def __init__(self, stmts):
        self.stmts = list(stmts)
        self.orig_lines = getattr(stmts, "lines", None)
        self.vars: dict[str, str] = {}  # mangled -> C declaration
        # name -> (ty, dims, rank); dims is a tuple of (lo, hi) int pairs for a
        # compile-time DIM, or None for a runtime (variable-bound) DIM
        self.arrays: dict[str, tuple[str, tuple[tuple[int, int], ...] | None, int]] = {}
        self.option_base = 0  # current OPTION BASE for int-bound DIMs
        self.fns: list[str] = []  # hoisted inline DEF FN definitions
        self.fn_names: set[str] = set()
        self.data: list[tuple[str, bool]] = []
        self.data_offset: dict[int, int] = {}  # top-level stmt index -> data cursor
        self.labels: set[int] = set()
        self.n = 0  # unique-label counter
        self.params: dict[str, str] = {}  # active DEF FN / SUB param name -> C lvalue
        self.subs: dict[str, tuple[str, ...]] = {}  # SUB name -> params
        self.in_sub = False
        self.uses_eh = False  # ON ERROR / RESUME / ERROR / ERR / ERL present

    def uid(self) -> int:
        self.n += 1
        return self.n

    # --- naming / declarations ---

    def var(self, name: str) -> str:
        if name in self.params:
            return self.params[name]
        if self.in_sub:
            # no corpus witness pins TB's local/shared default for SUB-body
            # variables, so only parameters are allowed inside a SUB for now
            raise _Unsupported(f"non-parameter variable {name} in SUB")
        cty, pre, zero = _VTYPES[_suffix_ty(name)]
        m = pre + _base(name)
        self.vars.setdefault(m, f"static {cty}{'' if cty.endswith('*') else ' '}{m} = {zero};")
        return m

    def array(self, name: str, rank: int):
        if name not in self.arrays:
            self.dim_array(name, (10,) * rank)  # implicit DIM x(10[,10])
        return self.arrays[name]

    def dim_array(self, name: str, bounds) -> list[str]:
        """Register array `name`; returns the allocation code (empty when static).

        Each DIM bound is an int upper bound (lower comes from OPTION BASE), an
        explicit `(lo, hi)` pair (`DIM A(0:4)`), or Exprs for runtime bounds."""
        rank = len(bounds)
        if rank > 2:
            raise _Unsupported("DIM rank > 2")
        ty = _suffix_ty(name)
        norm = [b if isinstance(b, tuple) else (self.option_base, b) for b in bounds]
        if all(isinstance(lo, int) and isinstance(hi, int) for lo, hi in norm):
            self.arrays[name] = (ty, tuple(norm), rank)
            return []
        # runtime bounds: heap allocation at the DIM statement
        self.arrays[name] = (ty, None, rank)
        _, pre, _ = _VTYPES[ty]
        m = "a" + pre + _base(name)
        code = []
        for k, (lo, hi) in enumerate(norm, 1):
            lo_c = str(lo) if isinstance(lo, int) else f"(long)tb_cint({self.num(lo)})"
            hi_c = str(hi) if isinstance(hi, int) else f"(long)tb_cint({self.num(hi)})"
            code.append(f"{m}_lo{k} = {lo_c}; {m}_n{k} = {hi_c} - {m}_lo{k} + 1;")
        total = " * ".join(f"{m}_n{k}" for k in range(1, rank + 1))
        code.append(f"{m} = tb_calloc({total}, sizeof *{m});")
        return code

    # --- expressions ---

    def num(self, e) -> str:
        """Render e as a C double-valued expression."""
        if isinstance(e, _Raw):
            return e.code
        if _is_str(e):
            raise _Unsupported(f"string expression where a number is needed: {e!r}")
        if isinstance(e, ir.Lit):
            return repr(float(e.value)) if isinstance(e.value, float) else str(e.value)
        if isinstance(e, (ir.DblLit, ir.SingleLit)):
            return repr(e.value)
        if isinstance(e, ir.HexLit):
            return f"(double)(short)0x{e.value:X}"
        if isinstance(e, ir.Var):
            return self.var(e.name)
        if isinstance(e, ir.ArrayRef):
            return self.aref(e)
        if isinstance(e, ir.Neg):
            return f"(-({self.num(e.operand)}))"
        if isinstance(e, ir.Not):
            return f"tb_not({self.num(e.operand)})"
        if isinstance(e, ir.Group):
            return f"({self.num(e.inner)})"
        if isinstance(e, (ir.Err, ir.Erl)):
            return "(double)tb_err" if isinstance(e, ir.Err) else "(double)tb_erl"
        if isinstance(e, ir.BinOp):
            if e.op == "/":
                return f"tb_div({self.num(e.lhs)}, {self.num(e.rhs)})"
            if e.op in "+-*":
                return f"({self.num(e.lhs)} {e.op} {self.num(e.rhs)})"
            if e.op == "^":
                return f"pow({self.num(e.lhs)}, {self.num(e.rhs)})"
            if e.op in _INT_BINOPS:
                return f"{_INT_BINOPS[e.op]}({self.num(e.lhs)}, {self.num(e.rhs)})"
            raise _Unsupported(f"operator {e.op}")
        if isinstance(e, (ir.RelOp, ir.LogOp)):
            return f"({self.cond(e)} ? -1.0 : 0.0)"  # TB truth value
        if isinstance(e, ir.Call):
            if e.name in ("UBOUND", "LBOUND"):
                return self.bound(e)
            return self.call(e, _NUM_FUNCS)
        if isinstance(e, ir.FnCall):
            return self.fncall(e)
        if isinstance(e, ir.Nullary):
            if e.name in _NULLARY:
                return _NULLARY[e.name]
            raise _Unsupported(f"intrinsic {e.name}")
        raise _Unsupported(f"expression {type(e).__name__}")

    def _nullary_str(self, e) -> str:
        if e.name in _NULLARY_STR:
            return _NULLARY_STR[e.name]
        raise _Unsupported(f"string intrinsic {e.name}")

    def s(self, e) -> str:
        """Render e as a C char*-valued expression."""
        if isinstance(e, _Raw):
            return e.code
        if isinstance(e, ir.StrLit):
            return _cstr(e.value)
        if isinstance(e, ir.Var):
            return self.var(e.name)
        if isinstance(e, ir.ArrayRef):
            return self.aref(e)
        if isinstance(e, ir.Group):
            return f"({self.s(e.inner)})"
        if isinstance(e, ir.BinOp) and e.op == "+":
            return f"tb_cat({self.s(e.lhs)}, {self.s(e.rhs)})"
        if isinstance(e, ir.Call):
            return self.call(e, _STR_FUNCS)
        if isinstance(e, ir.Nullary):
            return self._nullary_str(e)
        raise _Unsupported(f"string expression {type(e).__name__}")

    def call(self, e, table) -> str:
        # arity-keyed template; each arg renders by its own inferred type
        key = (e.name, len(e.args))
        if key not in table:
            raise _Unsupported(f"intrinsic {e.name}/{len(e.args)}")
        args = [self.s(a) if _is_str(a) else self.num(a) for a in e.args]
        return table[key].format(*args)

    def bound(self, e) -> str:
        # UBOUND(A(k)) / LBOUND(A(k)): the "index" is the dimension number
        (arg,) = e.args
        if not (isinstance(arg, ir.ArrayRef) and isinstance(arg.indices[0], ir.Lit)):
            raise _Unsupported(f"{e.name} with a non-constant dimension")
        k = int(arg.indices[0].value)
        ty, dims, rank = self.array(arg.name, 1)
        if not 1 <= k <= rank:
            raise _Unsupported(f"{e.name} dimension {k} of rank-{rank} array")
        _, pre, _ = _VTYPES[ty]
        m = "a" + pre + _base(arg.name)
        if dims is not None:
            lo, hi = dims[k - 1]
            return f"{lo if e.name == 'LBOUND' else hi}.0"
        if e.name == "LBOUND":
            return f"(double){m}_lo{k}"
        return f"(double)({m}_lo{k} + {m}_n{k} - 1)"

    def fncall(self, e) -> str:
        if e.name.endswith("$"):
            raise _Unsupported("string DEF FN")
        if e.name not in self.fn_names:
            raise _Unsupported(f"call to undefined {e.name}")
        return f"fn_{_base(e.name)}({', '.join(self.num(a) for a in e.args)})"

    def aref(self, e) -> str:
        if self.in_sub:
            raise _Unsupported("array access inside SUB (no SHARED witness)")
        ty, dims, rank = self.array(e.name, len(e.indices))
        if rank != len(e.indices):
            raise _Unsupported(f"rank mismatch on array {e.name}")
        _, pre, _ = _VTYPES[ty]
        m = "a" + pre + _base(e.name)
        idx = []
        for k, i in enumerate(e.indices, 1):
            lo = str(dims[k - 1][0]) if dims is not None else f"{m}_lo{k}"
            idx.append(f"((long)tb_cint({self.num(i)}) - {lo})")
        if rank == 1:
            return f"{m}[{idx[0]}]"
        stride = (
            str(dims[1][1] - dims[1][0] + 1) if dims is not None else f"{m}_n2"
        )
        return f"{m}[({idx[0]}) * {stride} + ({idx[1]})]"

    def cond(self, e) -> str:
        if isinstance(e, ir.RelOp):
            op = {"=": "==", "<>": "!="}.get(e.op, e.op)
            if _is_str(e.lhs) or _is_str(e.rhs):
                return f"(strcmp(tb_s({self.s(e.lhs)}), tb_s({self.s(e.rhs)})) {op} 0)"
            return f"({self.num(e.lhs)} {op} {self.num(e.rhs)})"
        if isinstance(e, ir.LogOp):
            c = "&&" if e.op == "AND" else "||"
            return f"({self.cond(e.lhs)} {c} {self.cond(e.rhs)})"
        # numeric-valued condition: TB nonzero = true
        return f"({self.num(e)} != 0)"

    # --- statements ---

    def assign(self, target, value) -> str:
        if isinstance(target, ir.Var):
            dst, ty = self.var(target.name), _suffix_ty(target.name)
        elif isinstance(target, ir.ArrayRef):
            dst, ty = self.aref(target), self.array(target.name, len(target.indices))[0]
        else:
            raise _Unsupported(f"assign target {type(target).__name__}")
        if ty == "STR":
            return f"{dst} = {self.s(value)};"
        return f"{dst} = {_STORE_CAST[ty].format(self.num(value))};"

    def gen_print(self, s) -> list[str]:
        out = []
        if s.file is not None:
            out.append(f"tb_out = tb_file({s.file}); tb_ch = {s.file};")
        for item in s.items:
            if isinstance(item, ir.Call) and item.name in ("TAB", "SPC"):
                out.append(f"tb_{item.name.lower()}({self.num(item.args[0])});")
            elif _is_str(item):
                out.append(f"tb_ps(tb_s({self.s(item)}));")
            else:
                out.append(f"tb_pn({self.num(item)});")
        if s.newline:
            out.append("tb_nl();")
        if s.file is not None:
            out.append("tb_out = stdout; tb_ch = 0;")
        return out

    def gen_write(self, s) -> list[str]:
        out = []
        if s.file is not None:
            out.append(f"tb_out = tb_file({s.file}); tb_ch = {s.file};")
        for k, item in enumerate(s.items):
            if k:
                out.append('tb_ps(",");')
            if _is_str(item):
                out.append(f"tb_wstr({self.s(item)});")
            else:
                out.append(f"tb_wnum({self.num(item)});")
        out.append("tb_nl();")
        if s.file is not None:
            out.append("tb_out = stdout; tb_ch = 0;")
        return out

    def gen_body(self, body, loops) -> list[str]:
        out = []
        i = 0
        body = list(body)
        while i < len(body):
            out.extend(self.gen(body[i], loops, None))
            i += 1
        return out

    def gen(self, s, loops, idx) -> list[str]:
        """C lines for one statement. `loops` is the open FOR/DO/WHILE label stack
        (shared across nesting so flat FOR..NEXT pairs match); `idx` is the
        top-level statement index or None inside a block body."""
        if self.in_sub and isinstance(
            s,
            (ir.Goto, ir.IfGoto, ir.Gosub, ir.Return, ir.OnGoto, ir.OnGosub,
             ir.OnError, ir.Resume),
        ):
            raise _Unsupported(f"{type(s).__name__} inside SUB (targets main labels)")
        if isinstance(s, ir.Assign):
            return [self.assign(s.target, s.value)]
        if isinstance(s, ir.Print):
            return self.gen_print(s)
        if isinstance(s, ir.Write):
            return self.gen_write(s)
        if isinstance(s, ir.End):
            return ["exit(0);"]
        if isinstance(s, (ir.Tron, ir.Troff)):
            return []
        if isinstance(s, ir.Goto):
            return [f"goto L{s.target};"]
        if isinstance(s, ir.IfGoto):
            return [f"if {self.cond(s.cond)} goto L{s.target};"]
        if isinstance(s, ir.Gosub):
            n = self.uid()
            return [f"tb_gstack[tb_gsp++] = &&R{n}; goto L{s.target}; R{n}:;"]
        if isinstance(s, ir.Return):
            return ["goto *tb_gstack[--tb_gsp];"]
        if isinstance(s, ir.OnGoto) or isinstance(s, ir.OnGosub):
            n = self.uid()
            lines = [f"switch ((int)tb_cint({self.num(s.selector)})) {{"]
            for k, t in enumerate(s.targets, 1):
                if isinstance(s, ir.OnGoto):
                    lines.append(f"case {k}: goto L{t};")
                else:
                    lines.append(f"case {k}: tb_gstack[tb_gsp++] = &&R{n}; goto L{t};")
            lines.append("}")
            if isinstance(s, ir.OnGosub):
                lines.append(f"R{n}:;")
            return lines
        if isinstance(s, ir.For):
            n = self.uid()
            v = self.var(s.var.name)
            lim, st = f"tb_lim{n}", f"tb_st{n}"
            self.vars[lim] = f"static double {lim} = 0;"
            self.vars[st] = f"static double {st} = 0;"
            loops.append(("FOR", n, s.var.name))
            return [
                self.assign(s.var, s.init),
                f"{lim} = {self.num(s.limit)}; {st} = {self.num(s.step)};",
                f"FCHK{n}: if (!({st} >= 0 ? {v} <= {lim} : {v} >= {lim})) goto FDONE{n};",
            ]
        if isinstance(s, ir.NextStmt):
            for j in range(len(loops) - 1, -1, -1):
                if loops[j][0] == "FOR" and loops[j][2] == s.var.name:
                    _, n, _ = loops.pop(j)
                    v = self.var(s.var.name)
                    cast = _STORE_CAST[_suffix_ty(s.var.name)]
                    stv = f"{v} = {cast.format(f'{v} + tb_st{n}')};"
                    return [stv, f"goto FCHK{n};", f"FDONE{n}:;"]
            raise _Unsupported(f"NEXT {s.var.name} without open FOR")
        if isinstance(s, ir.While):
            n = self.uid()
            loops.append(("WHILE", n, None))
            return [f"WTOP{n}: if (!{self.cond(s.cond)}) goto WDONE{n};"]
        if isinstance(s, ir.Wend):
            for j in range(len(loops) - 1, -1, -1):
                if loops[j][0] == "WHILE":
                    _, n, _ = loops.pop(j)
                    return [f"goto WTOP{n};", f"WDONE{n}:;"]
            raise _Unsupported("WEND without open WHILE")
        if isinstance(s, ir.Do):
            n = self.uid()
            loops.append(("DO", n, None))
            top = [f"DTOP{n}:;"]
            if s.kind == "WHILE":
                top.append(f"if (!{self.cond(s.cond)}) goto DDONE{n};")
            elif s.kind == "UNTIL":
                top.append(f"if {self.cond(s.cond)} goto DDONE{n};")
            return top
        if isinstance(s, ir.Loop):
            for j in range(len(loops) - 1, -1, -1):
                if loops[j][0] == "DO":
                    _, n, _ = loops.pop(j)
                    if s.kind == "WHILE":
                        return [f"if {self.cond(s.cond)} goto DTOP{n};", f"DDONE{n}:;"]
                    if s.kind == "UNTIL":
                        return [f"if (!{self.cond(s.cond)}) goto DTOP{n};", f"DDONE{n}:;"]
                    return [f"goto DTOP{n};", f"DDONE{n}:;"]
            raise _Unsupported("LOOP without open DO")
        if isinstance(s, ir.ExitFor):
            for kind, n, _ in reversed(loops):
                if kind == "FOR":
                    return [f"goto FDONE{n};"]
            raise _Unsupported("EXIT FOR outside FOR")
        if isinstance(s, ir.ExitLoop):
            for kind, n, _ in reversed(loops):
                if kind == "DO":
                    return [f"goto DDONE{n};"]
            raise _Unsupported("EXIT LOOP outside DO")
        if isinstance(s, ir.IfInline):
            return [f"if {self.cond(s.cond)} {{", *self.gen_body(s.body, loops), "}"]
        if isinstance(s, ir.IfBlock):
            lines = []
            for k, (cond, body) in enumerate(s.arms):
                kw = "if" if k == 0 else "} else if"
                lines.append(f"{kw} {self.cond(cond)} {{")
                lines.extend(self.gen_body(body, loops))
            if s.else_body is not None:
                lines.append("} else {")
                lines.extend(self.gen_body(s.else_body, loops))
            lines.append("}")
            return lines
        if isinstance(s, ir.SelectCase):
            n = self.uid()
            is_str = _is_str(s.selector)
            sel = f"tb_sel{n}"
            self.vars[sel] = f"static {'char *' if is_str else 'double '}{sel} = {'0' if is_str else '0'};"
            lines = [f"{sel} = {self.s(s.selector) if is_str else self.num(s.selector)};"]

            def guard(g) -> str:
                if isinstance(g, ir.CaseValue):
                    if is_str:
                        return f"(strcmp(tb_s({sel}), tb_s({self.s(g.value)})) == 0)"
                    return f"({sel} == {self.num(g.value)})"
                if isinstance(g, ir.CaseRange):
                    if is_str:
                        return (
                            f"(strcmp(tb_s({sel}), tb_s({self.s(g.lo)})) >= 0 && "
                            f"strcmp(tb_s({sel}), tb_s({self.s(g.hi)})) <= 0)"
                        )
                    return f"({sel} >= {self.num(g.lo)} && {sel} <= {self.num(g.hi)})"
                if isinstance(g, ir.CaseIs):
                    op = {"=": "==", "<>": "!="}.get(g.op, g.op)
                    if is_str:
                        return f"(strcmp(tb_s({sel}), tb_s({self.s(g.value)})) {op} 0)"
                    return f"({sel} {op} {self.num(g.value)})"
                raise _Unsupported(f"case guard {type(g).__name__}")

            for k, arm in enumerate(s.arms):
                kw = "if" if k == 0 else "} else if"
                lines.append(f"{kw} ({' || '.join(guard(g) for g in arm.guards)}) {{")
                lines.extend(self.gen_body(arm.body, loops))
            if s.case_else is not None:
                lines.append("} else {")
                lines.extend(self.gen_body(s.case_else, loops))
            lines.append("}")
            return lines
        if isinstance(s, ir.Dim):
            out = []
            for name, bounds in ((s.name, s.bounds), *s.also):
                out.extend(self.dim_array(name, bounds))
            return out
        if isinstance(s, ir.OptionBase):
            self.option_base = s.n  # lower bound of subsequent int-bound DIMs
            return []
        if isinstance(s, ir.Data):
            if idx is not None:
                self.data_offset[idx] = len(self.data)
            self.data.extend((it.text, it.is_str) for it in s.items)
            return []
        if isinstance(s, ir.Read):
            out = []
            for t in s.targets:
                ty = (
                    _suffix_ty(t.name)
                    if isinstance(t, (ir.Var, ir.ArrayRef))
                    else "NUM"
                )
                src = (
                    "tb_dup(tb_data[tb_data_p++])"
                    if ty == "STR"
                    else "tb_val(tb_data[tb_data_p++])"
                )
                out.append(self.assign(t, _Raw(src, ty == "STR")))
            return out
        if isinstance(s, ir.Restore):
            off = 0 if s.target is None else self.data_offset.get(s.target)
            if off is None:
                raise _Unsupported("RESTORE to a non-DATA statement")
            return [f"tb_data_p = {off};"]
        if isinstance(s, ir.Input):
            fn = "tb_input_str" if _suffix_ty(s.var.name) == "STR" else "tb_input_num"
            prompt = _cstr(s.prompt.value) if s.prompt is not None else "NULL"
            mark = "0" if (s.prompt is not None and s.comma) else "1"
            return [self.assign(s.var, _Raw(f"{fn}({prompt}, {mark})", fn.endswith("str")))]
        if isinstance(s, ir.LineInput):
            prompt = _cstr(s.prompt.value) if s.prompt is not None else "NULL"
            return [self.assign(s.var, _Raw(f"tb_input_str({prompt}, 0)", True))]
        if isinstance(s, ir.Swap):
            a, b = self.var(s.a.name), self.var(s.b.name)
            ta, tb_ = _suffix_ty(s.a.name), _suffix_ty(s.b.name)
            if ta != tb_:
                raise _Unsupported("SWAP across types")
            cty, _, _ = _VTYPES[ta]
            return [f"{{ {cty} t = {a}; {a} = {b}; {b} = t; }}"]
        if isinstance(s, ir.Beep):
            return ['tb_ps("\\a");']
        if isinstance(s, ir.Cls):
            return ['tb_ps("\\033[2J\\033[H"); tb_col = 0;']
        if isinstance(s, ir.Delay):
            return [f"tb_delay({self.num(s.secs)});"]
        if isinstance(s, ir.Randomize):
            return [f"srand((unsigned)tb_i({self.num(s.seed)}));"]
        if isinstance(s, ir.MidAssign):
            tgt = self.var(s.target.name)
            n = self.uid()
            return [
                f"{{ char *t{n} = tb_dup(tb_s({tgt})); const char *m{n} = tb_s({self.s(s.source)});",
                f"  long p{n} = tb_i({self.num(s.start)}) - 1, L{n} = (long)strlen(t{n});",
                f"  for (long k{n} = 0; m{n}[k{n}] && p{n} + k{n} < L{n}; k{n}++) t{n}[p{n} + k{n}] = m{n}[k{n}];",
                f"  {tgt} = t{n}; }}",
            ]
        if isinstance(s, ir.DefFn):
            self.gen_deffn(s)
            return []
        if isinstance(s, ir.SubDef):
            self.gen_subdef(s)
            return []
        if isinstance(s, ir.CallStmt):
            return self.gen_call(s)
        if isinstance(s, ir.ExitSub):
            if not self.in_sub:
                raise _Unsupported("EXIT SUB outside SUB")
            return ["return;"]
        if isinstance(s, ir.Open):
            mode = {"I": '"r"', "O": '"w"', "A": '"a"'}.get(s.mode.value.upper())
            if mode is None:
                raise _Unsupported(f"OPEN mode {s.mode.value!r}")
            return [f"tb_open({mode}, {s.num}, {self.s(s.file)});"]
        if isinstance(s, ir.Close):
            return [f"tb_close({s.num});"]
        if isinstance(s, ir.Reset):
            return ["tb_reset();"]
        if isinstance(s, ir.InputFile):
            out = []
            for t in s.vars:
                is_s = _suffix_ty(t.name) == "STR"
                fn = "tb_finput_str" if is_s else "tb_finput_num"
                out.append(self.assign(t, _Raw(f"{fn}({s.num})", is_s)))
            return out
        if isinstance(s, ir.OnError):
            if s.target is None:
                return ["tb_handler = 0;"]
            self.labels.add(s.target)
            return [f"tb_handler = &&L{s.target};"]
        if isinstance(s, ir.Resume):
            if s.target is not None:
                self.labels.add(s.target)
                return [f"goto L{s.target};"]
            return ["goto *tb_next;" if s.next_ else "goto *tb_stmt;"]
        if isinstance(s, ir.ErrorStmt):
            return [f"tb_error((int)tb_cint({self.num(s.code)}));"]
        if isinstance(s, ir.Erase):
            ty, dims, rank = self.array(s.name, 1)
            _, pre, _ = _VTYPES[ty]
            m = "a" + pre + _base(s.name)
            if dims is not None:
                return [f"memset({m}, 0, sizeof {m});"]
            return [f"free({m}); {m} = 0;"]
        if isinstance(s, ir.Key):
            return []  # soft-key display line: no modern-terminal counterpart
        if isinstance(s, ir.Locate):
            out = [f"tb_locate({self.num(s.row)}, {self.num(s.col)});"]
            if s.cursor is not None:
                out.append(
                    f'tb_ps(tb_i({self.num(s.cursor)}) ? "\\033[?25h" : "\\033[?25l");'
                )
            return out
        if isinstance(s, ir.Color):
            fg = self.num(s.fg) if s.fg is not None else "0"
            bg = self.num(s.bg) if s.bg is not None else "0"
            has_fg = "1" if s.fg is not None else "0"
            has_bg = "1" if s.bg is not None else "0"
            return [f"tb_color({has_fg}, {fg}, {has_bg}, {bg});"]
        if isinstance(s, ir.Shell):
            return [f"if (system({self.s(s.cmd)})) {{}}"]
        if isinstance(s, ir.Chdir):
            return [f"if (chdir({self.s(s.path)})) {{}}"]
        if isinstance(s, ir.Environ):
            return [f"putenv(tb_dup({self.s(s.s)}));"]
        if isinstance(s, ir.Kill):
            return [f"remove({self.s(s.file)});"]
        if isinstance(s, ir.Name):
            return [f"rename({self.s(s.old)}, {self.s(s.new)});"]
        raise _Unsupported(f"statement {type(s).__name__}")

    def gen_deffn(self, s) -> None:
        if s.is_block:
            raise _Unsupported("multi-line DEF FN")
        if s.name.endswith("$") or any(p.endswith("$") for p in s.params):
            raise _Unsupported("string DEF FN")
        old = self.params
        self.params = {p: f"p_{_base(p)}" for p in s.params}
        try:
            body = self.num(s.body)
        finally:
            self.params = old
        args = ", ".join(f"double p_{_base(p)}" for p in s.params) or "void"
        self.fns.append(f"static double fn_{_base(s.name)}({args}) {{ return {body}; }}")
        self.fn_names.add(s.name)

    def gen_subdef(self, s) -> None:
        if self.in_sub:
            raise _Unsupported("nested SUB")
        self.subs[s.name] = s.params
        old = self.params
        self.params = {p: f"(*p_{_base(p)})" for p in s.params}
        self.in_sub = True
        try:
            body = self.gen_body(s.body, [])
        finally:
            self.in_sub = False
            self.params = old
        sig = []
        for p in s.params:
            cty, _, _ = _VTYPES[_suffix_ty(p)]
            sig.append(f"{cty}{'' if cty.endswith('*') else ' '}*p_{_base(p)}")
        head = f"static void sub_{_base(s.name)}({', '.join(sig) or 'void'}) {{"
        self.fns.append("\n".join([head, *("    " + ln for ln in body), "}"]))

    def gen_call(self, s) -> list[str]:
        if s.name not in self.subs:
            raise _Unsupported(f"CALL to unknown SUB {s.name}")
        params = self.subs[s.name]
        if len(params) != len(s.args):
            raise _Unsupported(f"CALL {s.name}: arity mismatch")
        tmps, args = [], []
        for p, a in zip(params, s.args):
            ty = _suffix_ty(p)
            # a plain variable (or array element) of matching type passes by
            # reference, TB semantics (zz_sub1); anything else by value copy
            if isinstance(a, ir.Var) and _suffix_ty(a.name) == ty:
                args.append(f"&{self.var(a.name)}")
            elif (
                isinstance(a, ir.ArrayRef)
                and not self.in_sub
                and self.array(a.name, len(a.indices))[0] == ty
            ):
                args.append(f"&{self.aref(a)}")
            else:
                cty, _, _ = _VTYPES[ty]
                t = f"t{self.uid()}"
                val = self.s(a) if ty == "STR" else _STORE_CAST[ty].format(self.num(a))
                tmps.append(f"{cty}{'' if cty.endswith('*') else ' '}{t} = {val};")
                args.append(f"&{t}")
        call = f"sub_{_base(s.name)}({', '.join(args)});"
        if tmps:
            return ["{", *tmps, call, "}"]
        return [call]

    # --- whole program ---

    def build(self) -> str:
        # collect label targets and error-handling usage across the whole tree
        def walk(node):
            if isinstance(node, (ir.Goto, ir.IfGoto, ir.Gosub)):
                if isinstance(node.target, int):
                    self.labels.add(node.target)
            if isinstance(node, (ir.OnGoto, ir.OnGosub)):
                self.labels.update(t for t in node.targets if isinstance(t, int))
            if isinstance(node, (ir.OnError, ir.Resume)):
                self.uses_eh = True
                if isinstance(node.target, int):
                    self.labels.add(node.target)
            if isinstance(node, (ir.ErrorStmt, ir.Err, ir.Erl)):
                self.uses_eh = True
            for f in getattr(node, "__dataclass_fields__", ()):
                v = getattr(node, f)
                for item in v if isinstance(v, tuple) else (v,):
                    if hasattr(item, "__dataclass_fields__"):
                        walk(item)

        for st in self.stmts:
            walk(st)

        body: list[str] = []
        loops: list[tuple[str, int, str | None]] = []
        for i, st in enumerate(self.stmts):
            # ERL/tb_erl reports the emitted source's line numbers
            # (Program.lines when the error-trap table pinned them, else
            # 10, 20, ... -- the same rule emit0 applies)
            ln = self.orig_lines[i] if self.orig_lines is not None else 10 * (i + 1)
            if self.uses_eh:
                # every statement gets a label plus RESUME bookkeeping
                body.append(f"L{i}:;")
                body.append(f"tb_stmt = &&L{i}; tb_next = &&L{i + 1}; tb_erl = {ln};")
            else:
                if i in self.labels:
                    body.append(f"L{i}:;")
                body.append(f"tb_erl = {ln};")
            body.extend(self.gen(st, loops, i))
        if self.uses_eh:
            body.append(f"L{len(self.stmts)}:;")
        if loops:
            raise _Unsupported(f"unclosed loop(s): {[k for k, *_ in loops]}")

        parts = [_PRELUDE]
        if self.data:
            items = ", ".join(_cstr(t) for t, _ in self.data)
            parts.append(f"static const char *tb_data[] = {{ {items} }};")
            parts.append("static int tb_data_p = 0;")
        for name, (ty, dims, rank) in sorted(self.arrays.items()):
            cty, pre, _ = _VTYPES[ty]
            sep = "" if cty.endswith("*") else " "
            m = f"a{pre}{_base(name)}"
            if dims is not None:
                size = " * ".join(str(hi - lo + 1) for lo, hi in dims)
                parts.append(f"static {cty}{sep}{m}[{size}] = {{0}};")
            else:
                parts.append(f"static {cty}{sep}*{m} = 0;")
                for k in range(1, rank + 1):
                    parts.append(f"static long {m}_lo{k} = 0, {m}_n{k} = 0;")
        parts.extend(self.vars[k] for k in sorted(self.vars))
        parts.extend(self.fns)
        parts.append("int main(void) {")
        if self.uses_eh:
            # tb_error longjmps here; the installed handler label takes over
            parts.append("    if (setjmp(tb_env)) goto *tb_handler;")
        parts.extend("    " + ln for ln in body)
        parts.append("    return 0;")
        parts.append("}")
        return "\n".join(parts) + "\n"


def emit_c(stmts) -> str:
    """Typed IR statements -> a self-contained C translation unit (gcc/clang).

    Raises ValueError for programs using constructs outside the implemented
    vocabulary -- fail-loud, like the decoder."""
    return _Gen(stmts).build()
